FONT = '<w:rFonts w:ascii="Meiryo UI" w:eastAsia="Meiryo UI" w:hAnsi="Meiryo UI" w:hint="eastAsia"/>'
SUB_NUM_BASE = 900  # 小項目①の採番を見出しごとにリセットするための numId


def rpr(size=21, bold=False, color=None, underline=False, highlight=False):
    s = FONT
    if bold:
        s += "<w:b/><w:bCs/>"
    if color:
        s += f'<w:color w:val="{color}"/>'
    s += f'<w:sz w:val="{size}"/><w:szCs w:val="{size}"/>'
    if highlight:
        s += '<w:highlight w:val="yellow"/>'
    if underline:
        s += '<w:u w:val="single"/>'
    s += '<w:lang w:eastAsia="ja-JP"/>'
    return f"<w:rPr>{s}</w:rPr>"


def run(text, **kw):
    if not text:
        return ""
    return f'<w:r>{rpr(**kw)}<w:t xml:space="preserve">{escape(text)}</w:t></w:r>'


def rich(text, size=21):
    """【◎決定】【★宿題】を色付き太字に、「（!…）」を黄色ハイライトの話者表記にする。"""
    out = []
    for part in re.split(r"(【◎決定】|【★宿題】|（![^）]*）)", text):
        if part == "【◎決定】":
            out.append(run(part, size=size, bold=True, color="FF0000"))
        elif part == "【★宿題】":
            out.append(run(part, size=size, bold=True, color="0070C0"))
        elif part.startswith("（!"):
            out.append(run("（" + part[2:], size=size, highlight=True))
        else:
            out.append(run(part, size=size))
    return "".join(out)


def para(content, ppr_inner, size=21, bold=False):
    return f"<w:p><w:pPr>{ppr_inner}{rpr(size=size, bold=bold)}</w:pPr>{content}</w:p>"


HDR_PPR = '<w:spacing w:after="0" w:line="240" w:lineRule="auto"/>'


def header_para(line):
    if line.startswith("資料："):
        name = line.split("!", 1)[1]
        return para(run("資料： ") + run(name, highlight=True), HDR_PPR)
    return para(run(line), HDR_PPR)


def cell(width, paras_xml):
    return f'<w:tc><w:tcPr><w:tcW w:w="{width}" w:type="dxa"/></w:tcPr>{paras_xml}</w:tc>'


CELL_PPR = '<w:spacing w:line="220" w:lineRule="exact"/>'


def agenda_cell(title, sub):
    x = para(run(title, size=20, bold=True), CELL_PPR, size=20, bold=True)
    if sub:
        mark, name = sub.split(" ", 1)
        x += para(run(mark + " ", size=20) + run(name, size=20, underline=True), CELL_PPR, size=20)
    return x


def items_cell(items):
    if not items:
        return para(run("―", size=20),
                    '<w:pStyle w:val="a9"/><w:spacing w:after="0" w:line="220" w:lineRule="exact"/><w:ind w:left="113"/>', size=20)
    ppr = ('<w:pStyle w:val="a9"/><w:numPr><w:ilvl w:val="0"/><w:numId w:val="10"/></w:numPr>'
           '<w:spacing w:line="220" w:lineRule="exact"/><w:ind w:left="113" w:hanging="113"/>')
    return "".join(para(rich(t, size=20), ppr, size=20) for t in items)


def build_table(tbl_head, widths):
    rows = []
    for title, sub, dec, hw in SUMMARY:
        rows.append('<w:tr><w:trPr><w:trHeight w:val="20"/></w:trPr>'
                    + cell(widths[0], agenda_cell(title, sub))
                    + cell(widths[1], items_cell(dec))
                    + cell(widths[2], items_cell(hw)) + "</w:tr>")
    return tbl_head + "".join(rows) + "</w:tbl>"


def build_body():
    out, section, prev = [], 0, None
    for item in BODY:
        kind = item[0]
        if kind == 1 and prev in ("H", "S", "B", None):
            raise ValueError(f"➢（2段目）の前に●（1段目）がない: {item[1][:30]}")
        prev = kind
        if kind == "H":
            section += 1
            ppr = ('<w:pStyle w:val="a9"/><w:keepNext/><w:numPr><w:ilvl w:val="0"/><w:numId w:val="11"/></w:numPr>'
                   '<w:spacing w:after="0" w:line="240" w:lineRule="auto"/>')
            out.append(para(run(item[1], bold=True), ppr, bold=True))
        elif kind == "S":
            ppr = (f'<w:pStyle w:val="a9"/><w:keepNext/><w:numPr><w:ilvl w:val="0"/><w:numId w:val="{SUB_NUM_BASE + section}"/></w:numPr>'
                   '<w:spacing w:after="0" w:line="240" w:lineRule="auto"/>')
            out.append(para(run(item[1], underline=True), ppr))
        elif kind == "B":
            out.append(para("", '<w:pStyle w:val="a9"/><w:spacing w:after="0" w:line="240" w:lineRule="auto"/><w:ind w:left="440"/>'))
        else:
            ppr = (f'<w:pStyle w:val="a9"/><w:numPr><w:ilvl w:val="{kind}"/><w:numId w:val="17"/></w:numPr>'
                   '<w:spacing w:after="0" w:line="240" w:lineRule="auto"/>')
            out.append(para(rich(item[1]), ppr))
    return "".join(out), section


def main():
    with zipfile.ZipFile(TEMPLATE) as z:
        files = {n: z.read(n) for n in z.namelist()}
    doc = files["word/document.xml"].decode("utf8")

    head, body = doc.split("<w:body>", 1)
    tbl_start, tbl_end = body.index("<w:tbl>"), body.index("</w:tbl>") + len("</w:tbl>")
    pre_paras = re.findall(r"<w:p[ >].*?</w:p>", body[:tbl_start], flags=re.S)
    post = body[tbl_end:]
    post_paras = re.findall(r"<w:p[ >].*?</w:p>", post, flags=re.S)
    final_sect = re.search(r"<w:sectPr[ >](?:(?!<w:sectPr).)*?</w:sectPr>\s*</w:body>", post, flags=re.S).group(0)

    tbl = body[tbl_start:tbl_end]
    tbl_head = tbl[: tbl.index("</w:tblGrid>") + len("</w:tblGrid>")]
    header_row = re.findall(r"<w:tr[ >].*?</w:tr>", tbl, flags=re.S)[0]
    widths = [int(w) for w in re.findall(r'<w:gridCol w:w="(\d+)"/>', tbl_head)]

    # ひな型の先頭罫線(0)・資料下罫線(14)・表前のセクション区切り(15)と、凡例ブロック(0-8)はそのまま使う
    parts = [pre_paras[0]]
    parts += [header_para(l) for l in HEADER_LINES]
    parts += [pre_paras[14], pre_paras[15]]
    parts.append(build_table(tbl_head + header_row, widths))
    parts += post_paras[0:9]
    body_xml, n_sections = build_body()
    parts.append(body_xml)

    new_doc = head + "<w:body>" + "".join(parts) + final_sect + "</w:document>"
    files["word/document.xml"] = new_doc.encode("utf8")

    numbering = files["word/numbering.xml"].decode("utf8")
    extra = "".join(
        f'<w:num w:numId="{SUB_NUM_BASE + i}"><w:abstractNumId w:val="1"/>'
        f'<w:lvlOverride w:ilvl="0"><w:startOverride w:val="1"/></w:lvlOverride></w:num>'
        for i in range(1, n_sections + 1))
    last_num_end = numbering.rindex("</w:num>") + len("</w:num>")
    files["word/numbering.xml"] = (numbering[:last_num_end] + extra + numbering[last_num_end:]).encode("utf8")

    core = files["docProps/core.xml"].decode("utf8")
    core = re.sub(r"<dc:creator>.*?</dc:creator>", "<dc:creator></dc:creator>", core, flags=re.S)
    core = re.sub(r"<cp:lastModifiedBy>.*?</cp:lastModifiedBy>", "<cp:lastModifiedBy></cp:lastModifiedBy>", core, flags=re.S)
    core = re.sub(r"<dc:title>.*?</dc:title>", "<dc:title></dc:title>", core, flags=re.S)
    files["docProps/core.xml"] = core.encode("utf8")

    tmp = OUTPUT + ".tmp"
    with zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as z:
        for name, data in files.items():
            z.writestr(name, data)
    shutil.move(tmp, OUTPUT)
    print(f"written: {OUTPUT}  sections={n_sections}  table_rows={len(SUMMARY)}  body_items={len(BODY)}")


main()
