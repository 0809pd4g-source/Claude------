    items = [(i, dict(anchor=a, target=t, comment=c)) for i, (a, t, c) in enumerate(rows, 1)]
    unplaced = cg.annotate(str(minutes), str(out), items)
    print(out.name, f'コメント枠 {len(items) - len(unplaced)}件', '貼れなかったもの: ' + '、'.join(f'No.{n}' for n, _ in unplaced) if unplaced else '')


